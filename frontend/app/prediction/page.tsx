"use client";

import { useMemo, useState } from "react";
import { FiLoader } from "react-icons/fi";

import {
  DecisionBadge,
  Eyebrow,
  PageShell,
  Section,
  SiteFooter,
} from "@/components/finance-shell";
import {
  PredictionMode,
  PredictionSignal,
  STOCK_TICKERS,
  predictDaily,
  predictIntraday,
} from "@/lib/api";

function formatNumber(value: unknown, digits = 2) {
  const number = Number(value);
  if (!Number.isFinite(number)) return "—";
  return number.toLocaleString(undefined, {
    maximumFractionDigits: digits,
    minimumFractionDigits: digits,
  });
}

function confidencePercent(signal: PredictionSignal | null) {
  if (!signal) return 0;
  const value = Number(signal.predicted_probability);
  if (!Number.isFinite(value)) return 0;
  return Math.max(0, Math.min(100, value * 100));
}

export default function PredictionPage() {
  const [ticker, setTicker] = useState("AAPL");
  const [mode, setMode] = useState<PredictionMode>("daily");
  const [signal, setSignal] = useState<PredictionSignal | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const confidence = useMemo(() => confidencePercent(signal), [signal]);

  async function handlePrediction() {
    setLoading(true);
    setError("");
    setSignal(null);

    try {
      const result =
        mode === "daily" ? await predictDaily(ticker) : await predictIntraday(ticker);
      setSignal(result);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Prediction failed. Please try again.");
    } finally {
      setLoading(false);
    }
  }

  const indicators = signal
    ? [
        ["Current Price", `$${formatNumber(signal.current_price)}`],
        ["RSI", formatNumber(signal.RSI)],
        ["EMA 20", formatNumber(signal.EMA_20)],
        ["EMA 50", formatNumber(signal.EMA_50)],
        ["ATR", formatNumber(signal.ATR)],
      ]
    : [];

  return (
    <PageShell>
      <Section className="pt-32 sm:pt-36">
        <Eyebrow>Deployed HF Model API</Eyebrow>
        <div className="grid gap-10 lg:grid-cols-[0.9fr_1.1fr]">
          <div>
            <h1 className="text-4xl font-black text-white sm:text-5xl">Prediction Console</h1>
            <p className="mt-5 text-lg leading-8 text-slate-300">
              Select a ticker and horizon to query the deployed LSTM Attention model for confidence,
              indicators, and a decision signal.
            </p>
            <p className="mt-5 rounded-lg border border-amber-300/30 bg-amber-400/10 p-4 text-sm leading-6 text-amber-100">
              The decision is generated by the deployed LSTM Attention model and should be used only
              for paper trading or research.
            </p>
          </div>

          <div className="rounded-lg border border-white/10 bg-white/[0.04] p-5 shadow-2xl shadow-black/30">
            <div className="grid gap-4 sm:grid-cols-2">
              <label className="block">
                <span className="text-sm font-semibold text-slate-300">Ticker</span>
                <select
                  value={ticker}
                  onChange={(event) => setTicker(event.target.value)}
                  className="mt-2 w-full rounded-lg border-white/10 bg-slate-950 text-white focus:border-emerald-300 focus:ring-emerald-300"
                >
                  {STOCK_TICKERS.map((symbol) => (
                    <option key={symbol} value={symbol}>
                      {symbol}
                    </option>
                  ))}
                </select>
              </label>

              <label className="block">
                <span className="text-sm font-semibold text-slate-300">Prediction Mode</span>
                <select
                  value={mode}
                  onChange={(event) => setMode(event.target.value as PredictionMode)}
                  className="mt-2 w-full rounded-lg border-white/10 bg-slate-950 text-white focus:border-emerald-300 focus:ring-emerald-300"
                >
                  <option value="daily">Daily / Next Day</option>
                  <option value="intraday">Intraday / 5-minute</option>
                </select>
              </label>
            </div>

            <button
              type="button"
              onClick={handlePrediction}
              disabled={loading}
              className="mt-5 inline-flex w-full items-center justify-center gap-2 rounded-lg bg-emerald-400 px-5 py-3 text-sm font-bold text-slate-950 transition hover:bg-emerald-300 disabled:cursor-not-allowed disabled:opacity-60"
            >
              {loading && <FiLoader className="h-4 w-4 animate-spin" aria-hidden="true" />}
              {loading ? "Fetching prediction" : "Get Prediction"}
            </button>

            {error && (
              <div className="mt-5 rounded-lg border border-rose-300/30 bg-rose-400/10 p-4 text-sm text-rose-100">
                {error}
              </div>
            )}
          </div>
        </div>
      </Section>

      <Section className="py-12">
        <div className="rounded-lg border border-white/10 bg-white/[0.04] p-5 md:p-7">
          <div className="flex flex-col gap-5 md:flex-row md:items-center md:justify-between">
            <div>
              <p className="text-sm font-semibold uppercase tracking-wide text-slate-400">Model Output</p>
              <h2 className="mt-2 text-3xl font-black text-white">
                {signal ? `${signal.ticker} ${String(signal.mode).toUpperCase()}` : "Awaiting signal"}
              </h2>
              {signal?.ticker_id !== undefined && (
                <p className="mt-2 text-sm text-slate-400">Ticker ID: {String(signal.ticker_id)}</p>
              )}
            </div>
            <DecisionBadge decision={signal?.decision} />
          </div>

          <div className="mt-8 grid gap-6 lg:grid-cols-[300px_1fr]">
            <div className="rounded-lg border border-white/10 bg-slate-950/60 p-5">
              <p className="text-sm font-semibold text-slate-300">Confidence</p>
              <p className="mt-4 text-5xl font-black text-white">{formatNumber(confidence, 1)}%</p>
              <div className="mt-5 h-3 rounded-full bg-slate-800">
                <div
                  className="h-3 rounded-full bg-emerald-400 transition-all"
                  style={{ width: `${confidence}%` }}
                />
              </div>
              <p className="mt-4 text-xs leading-5 text-slate-500">
                Probability returned by the hosted prediction service.
              </p>
            </div>

            <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
              {indicators.length > 0 ? (
                indicators.map(([label, value]) => (
                  <div key={label} className="rounded-lg border border-white/10 bg-slate-950/60 p-5">
                    <p className="text-sm text-slate-400">{label}</p>
                    <p className="mt-3 text-2xl font-black text-white">{value}</p>
                  </div>
                ))
              ) : (
                <div className="rounded-lg border border-dashed border-white/10 p-5 text-sm text-slate-400 sm:col-span-2 lg:col-span-3">
                  Run a prediction to populate the decision, confidence, and indicator cards.
                </div>
              )}
            </div>
          </div>
        </div>
      </Section>

      <SiteFooter />
    </PageShell>
  );
}

